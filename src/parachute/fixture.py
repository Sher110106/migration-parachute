"""Deterministic local fixture. All rows are fictional (emails use the reserved
``.test`` domain); nothing here touches a real database."""

from __future__ import annotations

from dataclasses import dataclass

import psycopg
from psycopg.conninfo import conninfo_to_dict, make_conninfo

from .domain import LookupBackfillChange, MigrationSpec

DEFAULT_DSN = "postgresql:///parachute_demo"


@dataclass(frozen=True)
class FixtureProfile:
    customers: int = 2_000
    orders: int = 10_000
    with_dependent_view: bool = False


DEMO = FixtureProfile()
STRESS = FixtureProfile(customers=20_000, orders=100_000)


def _admin_dsn(dsn: str) -> tuple[str, str]:
    params = conninfo_to_dict(dsn)
    dbname = params.get("dbname") or "parachute_demo"
    params["dbname"] = "postgres"
    return make_conninfo(**params), dbname


def reset_database(dsn: str) -> None:
    admin, dbname = _admin_dsn(dsn)
    if not dbname.startswith("parachute"):
        raise ValueError("refusing to reset a database whose name does not start with 'parachute'")
    with psycopg.connect(admin, autocommit=True) as conn:
        conn.execute(f'DROP DATABASE IF EXISTS "{dbname}" WITH (FORCE)')
        conn.execute(f'CREATE DATABASE "{dbname}"')


def seed(dsn: str, profile: FixtureProfile = DEMO) -> str:
    """Create and fill the fixture tables. Returns the fixture checksum."""
    n, m = profile.customers, profile.orders
    with psycopg.connect(dsn, autocommit=True) as conn, conn.transaction():
        conn.execute(
            "CREATE TABLE customers ("
            " id bigint PRIMARY KEY,"
            " email text NOT NULL UNIQUE,"
            " name text NOT NULL,"
            " created_at timestamptz NOT NULL)"
        )
        conn.execute(
            "CREATE TABLE orders ("
            " id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            " customer_email text NOT NULL,"
            " amount_cents integer NOT NULL,"
            " status text NOT NULL,"
            " created_at timestamptz NOT NULL)"
        )
        conn.execute(
            "INSERT INTO customers SELECT g, 'customer' || g || '@fixture.test', 'Fixture customer ' || g, "
            "timestamptz '2026-01-01 00:00+00' + g * interval '1 hour' FROM generate_series(1, %s) g",
            (n,),
        )
        conn.execute(
            "INSERT INTO orders SELECT g, 'customer' || (((g * 7919) %% %s) + 1) || '@fixture.test', "
            "((g * 37) %% 10000) + 100, (ARRAY['paid','shipped','refunded'])[1 + g %% 3], "
            "timestamptz '2026-02-01 00:00+00' + g * interval '1 minute' FROM generate_series(1, %s) g",
            (n, m),
        )
        conn.execute("SELECT setval(pg_get_serial_sequence('orders', 'id'), %s)", (m,))
        if profile.with_dependent_view:
            conn.execute("CREATE VIEW order_contacts AS SELECT id, customer_email FROM orders")
    with psycopg.connect(dsn, autocommit=True) as conn:
        conn.execute("ANALYZE customers")
        conn.execute("ANALYZE orders")
    return fixture_checksum(dsn)


def fixture_checksum(dsn: str) -> str:
    with psycopg.connect(dsn, autocommit=True) as conn:
        row = conn.execute(
            "SELECT md5((SELECT string_agg(id || ':' || email, ',' ORDER BY id) FROM customers) || '|' || "
            "(SELECT string_agg(id || ':' || customer_email || ':' || amount_cents, ',' ORDER BY id) FROM orders))"
        ).fetchone()
    return row[0]


def demo_spec(fingerprint: str, **overrides) -> MigrationSpec:
    base = dict(
        migration_id="orders_customer_fk",
        database_fingerprint=fingerprint,
        target_table="orders",
        primary_key="id",
        change=LookupBackfillChange(
            old_column="customer_email",
            new_column="customer_id",
            new_type="bigint",
            lookup_table="customers",
            lookup_match_column="email",
            lookup_value_column="id",
        ),
    )
    base.update(overrides)
    return MigrationSpec(**base)
